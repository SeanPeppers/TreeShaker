"""Shadow probe noise-floor detection module."""

import numpy as np
import pandas as pd


def generate_shadow_probes(
    X: pd.DataFrame, n_probes: int, random_seed: int
) -> pd.DataFrame:
    """Generate shadow probes by randomly selecting and shuffling columns from X.

    Each shadow probe is generated by randomly selecting an existing feature column,
    and independently shuffling its rows to destroy its relationship with the target.

    Args:
        X: The input feature DataFrame.
        n_probes: Number of shadow probes to generate.
        random_seed: Seed for random number generation.

    Returns:
        DataFrame containing shadow probe columns named '__shadow_probe_0__',
        '__shadow_probe_1__', etc.
    """
    if X.empty or n_probes <= 0:
        return pd.DataFrame(index=X.index)

    rng = np.random.default_rng(random_seed)
    # Select columns with replacement, in case n_probes > number of features
    chosen_cols = rng.choice(X.columns, size=n_probes, replace=True)

    probes = {}
    for i, col in enumerate(chosen_cols):
        values = X[col].values
        # Independently shuffle values for the probe column
        shuffled = rng.permutation(values)
        probes[f"__shadow_probe_{i}__"] = pd.Series(
            shuffled, index=X.index, dtype=X[col].dtype
        )

    return pd.DataFrame(probes, index=X.index)


def compute_probe_threshold(probe_importances: np.ndarray, percentile: float) -> float:
    """Compute the noise-floor threshold from probe importances.

    Args:
        probe_importances: Array of importances for all shadow probes.
        percentile: Percentile value to use for the threshold (0-100).

    Returns:
        The calculated threshold value as a float.
    """
    if len(probe_importances) == 0:
        return 0.0
    return float(np.percentile(probe_importances, percentile))


def add_shadow_probe_warnings(
    results: pd.DataFrame, probe_threshold: float
) -> pd.DataFrame:
    """Flag features whose importance falls below the probe threshold.

    Adds a boolean 'shadow_probe_flag' column, which is True if the
    feature's 'shap_importance' is less than or equal to probe_threshold.

    Args:
        results: Results DataFrame.
        probe_threshold: The noise-floor threshold value.

    Returns:
        A copy of the results DataFrame with the shadow_probe_flag column added.
    """
    results = results.copy()
    results["shadow_probe_flag"] = results["shap_importance"] <= probe_threshold
    return results
